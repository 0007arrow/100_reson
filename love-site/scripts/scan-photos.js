/**
 * scan-photos.js
 * Scans the 'photos' folder for images (.jpg, .jpeg, .png, .webp, .gif, .avif)
 * and generates 'js/photos.js' with proper paths and friendly romantic captions.
 *
 * Usage:
 *   node scripts/scan-photos.js
 *   or: npm run photos
 */

const fs = require('fs');
const path = require('path');

const PHOTOS_DIR = path.resolve(__dirname, '../photos');
const OUTPUT_FILE = path.resolve(__dirname, '../js/photos.js');

const VALID_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif']);

// Romantic default captions when photos have camera/whatsapp generic names
const SWEET_CAPTIONS = [
  "My Beautiful Azra Baby ♥",
  "That Gorgeous Smile",
  "Pure Sunshine",
  "My Favorite Person In The World",
  "Unforgettable Moment",
  "Cherished Memory",
  "The Love of My Life",
  "Simply Breathtaking",
  "My Sweetheart Always",
  "My Angel & My Home",
  "Laughter & Joy With You",
  "Forever Captured in My Heart",
  "Endless Warmth",
  "My Whole Universe"
];

function formatCaption(fileName, index) {
  // Strip extension
  const nameWithoutExt = fileName.replace(/\.[^/.]+$/, '');

  // Detect generic camera / chat export filenames (e.g., "WhatsApp Image...", "IMG_...", "PXL_...")
  const isGeneric = /^(whatsapp[\s_-]?image|img[\s_-]?\d|pxl[\s_-]?\d|dsc[\s_-]?\d|screenshot|photo)/i.test(nameWithoutExt);

  if (isGeneric) {
    return SWEET_CAPTIONS[index % SWEET_CAPTIONS.length];
  }

  // Replace underscores and hyphens with spaces
  let formatted = nameWithoutExt.replace(/[-_]+/g, ' ').trim();
  
  // Remove leading numbers like "01.", "01 -", "1_", etc.
  formatted = formatted.replace(/^\d+[\s._-]+/, '');
  
  // Capitalize words nicely if it's all lowercase
  if (formatted && formatted === formatted.toLowerCase()) {
    formatted = formatted.replace(/\b\w/g, char => char.toUpperCase());
  }
  
  return formatted || SWEET_CAPTIONS[index % SWEET_CAPTIONS.length];
}

function scanPhotos() {
  console.log(`[Photo Scanner] Scanning folder: ${PHOTOS_DIR}`);

  if (!fs.existsSync(PHOTOS_DIR)) {
    console.warn(`[Photo Scanner] Warning: Photos directory does not exist at ${PHOTOS_DIR}`);
    fs.mkdirSync(PHOTOS_DIR, { recursive: true });
  }

  const entries = fs.readdirSync(PHOTOS_DIR, { withFileTypes: true });

  const photoList = [];

  for (const entry of entries) {
    if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      if (VALID_EXTENSIONS.has(ext)) {
        photoList.push({
          src: `photos/${encodeURIComponent(entry.name)}`,
          fileName: entry.name
        });
      }
    }
  }

  // Natural sort by filename
  photoList.sort((a, b) => a.fileName.localeCompare(b.fileName, undefined, { numeric: true, sensitivity: 'base' }));

  // Assign captions
  photoList.forEach((item, idx) => {
    item.caption = formatCaption(item.fileName, idx);
  });

  const fileContent = `/**
 * Auto-generated by scripts/scan-photos.js
 * To update this list after dropping photos into /photos, run:
 *   npm run photos
 */

const PHOTOS = ${JSON.stringify(photoList, null, 2)};

// Make available for both browser and Node/testing environments
if (typeof module !== 'undefined' && module.exports) {
  module.exports = PHOTOS;
}
`;

  fs.writeFileSync(OUTPUT_FILE, fileContent, 'utf-8', { flag: 'w' });

  console.log(`[Photo Scanner] Successfully updated ${OUTPUT_FILE}`);
  console.log(`[Photo Scanner] Found ${photoList.length} photo(s):`);
  photoList.forEach((p, i) => console.log(`   ${i + 1}. ${p.fileName} => "${p.caption}"`));
}

scanPhotos();
